# Стартовые характеристики героя
health = 100
gold = 0
potions = 1

# Номер комнаты и всего комнат
room = 1
rooms_total = 4

# Обыскали ли уже текущую комнату
searched = False

# Имя героя
name = input("Как зовут героя? ").strip()
if name == "":
    name = "Безымянный"

print()
print("=" * 50)
print("ТАЙНИК В СТАРОЙ БАШНЕ")
print("=" * 50)
print(name + ", ты входишь в старую башню.")
print("Где-то наверху спрятаны сокровища.")
print("В башне 4 комнаты. Каждый ход голод отнимает 5 здоровья.")
print("=" * 50)

# Основной цикл: игра идёт, пока герой жив
while health > 0:
    # Голод отнимает здоровье в начале каждого хода
    health = health - 5
    if health <= 0:
        break

    # Если здоровья мало — предупреждаем
    if health < 30:
        print("\n!! Здоровье на исходе. Может, выпить зелье?")

    print()
    print("-" * 50)
    print("Комната", room, "из", rooms_total)
    print("Здоровье:", health, "| Золото:", gold, "| Зелья:", potions)
    print()
    print("1 - Идти дальше")
    print("2 - Обыскать комнату")
    print("3 - Выпить зелье")

    choice = input("Твой выбор: ").strip()

    if choice == "1":
        # В последней комнате «идти дальше» значит выйти из башни
        if room == rooms_total:
            print("\nТы открываешь тяжёлую дверь и находишь сокровищницу!")
            gold = gold + 100
            break
        else:
            room = room + 1
            searched = False
            print("\nТы переходишь в следующую комнату.")

    elif choice == "2":
        if searched:
            print("\nЗдесь уже всё обыскано.")
        else:
            searched = True

            if room == 1:
                print("\nНа полке лежит старый кошель. +20 золота.")
                gold = gold + 20

            elif room == 2:
                print("\nТы задеваешь растяжку. Стрела в плечо! -30 здоровья.")
                health = health - 30
                print("Но в тайнике под полом ты находишь +15 золота.")
                gold = gold + 15

            elif room == 3:
                print("\nКрыса кусает тебя за руку! -15 здоровья.")
                health = health - 15
                print("Зато в углу лежит зелье. +1 зелье.")
                potions = potions + 1

            else:
                print("\nСтену охраняет ржавый доспех. Он бьёт тебя! -20 здоровья.")
                health = health - 20
                print("Зато в сундуке +50 золота.")
                gold = gold + 50

    elif choice == "3":
        if potions <= 0:
            print("\nЗелий больше нет.")
        elif health >= 100:
            print("\nЗдоровье и так полное. Зелье пока не нужно.")
        else:
            potions = potions - 1
            health = health + 30
            if health > 100:
                health = 100
            print("\nТы пьёшь зелье: +30 здоровья.")

    else:
        print("\nЯ не понял тебя. Введи 1, 2 или 3.")

# Итог игры
print()
print("=" * 50)
if health > 0:
    print("ПОБЕДА!")
    print(name, "выбирается из башни с", gold, "золота.")
else:
    print("Ты не выдержал голода и остался в башне навсегда.")
    print("Собрано золота:", gold)
print("=" * 50)
print("=== ИГРА ЗАВЕРШЕНА ===")
